final class bank_locator {
    /**
     * Returns the schema-setting names for the course question banks and their sections.
     *
     * The names follow the standard activity and section setting names generated by
     * the Moodle backup plan.
     *
     * @param int $courseid Course identifier.
     * @return array{qbanks: string[], sections: string[]} Backup setting names.
     */
    public static function get_backup_setting_names(int $courseid): array {
        global $DB;

        $sql = "SELECT cm.id AS cmid, cm.section AS sectionid
                  FROM {course_modules} cm
                  JOIN {modules} m ON m.id = cm.module
                 WHERE cm.course = :courseid
                   AND m.name = :modname
                   AND cm.deletioninprogress = 0
              ORDER BY cm.section, cm.id";

        $records = $DB->get_records_sql($sql, [
            'courseid' => $courseid,
            'modname' => 'qbank',
        ]);

        $qbanks = [];
        $sections = [];
        foreach ($records as $record) {
            $qbanks[] = 'setting_activity_qbank_' . $record->cmid . '_included';
            $sections[(int) $record->sectionid] =
                'setting_section_section_' . $record->sectionid . '_included';
        }

        return [
            'qbanks' => $qbanks,
            'sections' => array_values($sections),
        ];
    }
}
